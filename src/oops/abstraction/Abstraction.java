	//A method which is declare with help of "abstract keyword" and ended with semicolon(;) is known as "Abstract Method".
	//Abstract method applicable only for non-static method.
	
//iii)Concrete class
	//A class which is not declare with help of abstract keyword is known as "concrete class".
	
