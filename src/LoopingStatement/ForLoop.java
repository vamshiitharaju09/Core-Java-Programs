package LoopingStatement;
//When we know how many times to repeat the task,then we can go for "for loop".
// Q)Write a java program to print java for five times.
public class ForLoop {
	public static void main(String[]args)
	{
		for(int i=1;i<=5;i++)
		{
			System.out.println("JAVA");
			
		}
	}

}
