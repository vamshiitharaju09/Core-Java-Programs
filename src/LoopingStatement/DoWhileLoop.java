package LoopingStatement;
//Do while loop is similar to the while loop ,which is keeps on executing until the condition fixed.
// Here first it will execute set of instruction then it will check the condition.
public class DoWhileLoop {
	public static void main(String[]args)
	{
		int i=1;
		do {
			System.out.println(i);
			i++;
		}
		while(i<=5);
	}

}
