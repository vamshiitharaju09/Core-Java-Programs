package LoopingStatement;
//While loop is keeps on executing until the condition false.
//When we know and when we don't know how many times to repeat, the task then we can go for while looping statement.
public class WhileLoop {
	public static void main(String[]args)
	{
		int i=1;
		while(i<=10)
		{
			System.out.println(i);
			i++;
		}
	}

}
