package conditionalStatement;
//if-else
//else is a keyword which is used to create a else block.
//else block will be executed when if condition is false.
//with help of if else block we can achieve both positive and negative scenarios.
// one if block should contain only one else block.
public class IfElse {
public static void main(String[]args)
{
	System.out.println("Start");
	if(false)
	{
		System.out.println("RCB");
	}
	else
	{
		System.out.println("SRH");
	}
	
	System.out.println("END");
}
}
